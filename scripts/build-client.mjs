import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const source = readFileSync(new URL('src/client.js', root), 'utf8');
const lifecycle = readFileSync(new URL('src/skin-lifecycle.mjs', root), 'utf8').replace('export function', 'function');
const hooks = readFileSync(new URL('skin/hooks.mjs', root), 'utf8').replace('export default function', 'function');
writeFileSync(new URL('client.js', root), ('// Generated by scripts/build-client.mjs.\n' +
  source.replace('/* BUNDLED_SKIN_RUNTIME */', hooks + '\n' + lifecycle)).replace(/\r\n/g, '\n'));
